bool ensure_ca_certificate(const std::string &certPath, const std::string &keyPath) {
  // Check if both files already exist and are non-empty
  struct stat stCert, stKey;
  if (stat(certPath.c_str(), &stCert) == 0 && stCert.st_size > 0 &&
      stat(keyPath.c_str(), &stKey) == 0 && stKey.st_size > 0) {
    return true;
  }

  // Generate a new 2048-bit RSA key and self-signed CA certificate
  EVP_PKEY *pkey = EVP_RSA_gen(2048);
  if (!pkey) {
    std::cerr << "Failed to generate RSA key for CA\n";
    return false;
  }

  X509 *x509 = X509_new();
  if (!x509) {
    EVP_PKEY_free(pkey);
    return false;
  }

  ASN1_INTEGER_set(X509_get_serialNumber(x509), 1);
  X509_gmtime_adj(X509_get_notBefore(x509), 0);
  X509_gmtime_adj(X509_get_notAfter(x509), 31536000L * 5); // 5 years

  X509_set_pubkey(x509, pkey);

  X509_NAME *name = X509_get_subject_name(x509);
  X509_NAME_add_entry_by_txt(name, "C", MBSTRING_ASC, (const unsigned char *)"US", -1, -1, 0);
  X509_NAME_add_entry_by_txt(name, "O", MBSTRING_ASC, (const unsigned char *)"lmproxy Intercept CA", -1, -1, 0);
  X509_NAME_add_entry_by_txt(name, "CN", MBSTRING_ASC, (const unsigned char *)"lmproxy Root CA", -1, -1, 0);
  X509_set_issuer_name(x509, name);

  // Add Basic Constraints: CA:TRUE
  BASIC_CONSTRAINTS *bc = BASIC_CONSTRAINTS_new();
  bc->ca = 1;
  X509_add1_ext_i2d(x509, NID_basic_constraints, bc, 1, X509V3_ADD_DEFAULT);
  BASIC_CONSTRAINTS_free(bc);

  // Sign with key
  if (!X509_sign(x509, pkey, EVP_sha256())) {
    X509_free(x509);
    EVP_PKEY_free(pkey);
    return false;
  }

  // Write private key
  FILE *fKey = fopen(keyPath.c_str(), "wb");
  if (!fKey) {
    X509_free(x509);
    EVP_PKEY_free(pkey);
    return false;
  }
  PEM_write_PrivateKey(fKey, pkey, nullptr, nullptr, 0, nullptr, nullptr);
  fclose(fKey);

  // Write certificate
  FILE *fCert = fopen(certPath.c_str(), "wb");
  if (!fCert) {
    X509_free(x509);
    EVP_PKEY_free(pkey);
    return false;
  }
  PEM_write_X509(fCert, x509);
  fclose(fCert);

  X509_free(x509);
  EVP_PKEY_free(pkey);
  return true;
}

std::string prepare_squid_conf(const ProxyConfig &cfg, const std::string &workDir) {
  if (!cfg.customConfigFile.empty()) {
    return cfg.customConfigFile;
  }

  std::string confPath = workDir + "/squid.conf";
  std::ofstream out(confPath);
  if (!out) {
    throw std::runtime_error("Failed to write squid configuration to " + confPath);
  }

  out << "# Ephemeral squid configuration generated by lmproxy\n\n";

  // Listener configuration
  if (cfg.sslBump) {
    std::string cert = cfg.caCertPath.empty() ? (workDir + "/ca.pem") : cfg.caCertPath;
    std::string key = cfg.caKeyPath.empty() ? (workDir + "/ca.key") : cfg.caKeyPath;
    ensure_ca_certificate(cert, key);

    if (cfg.mode == "intercept") {
      out << "http_port " << cfg.bindAddress << ":" << cfg.port << " intercept\n";
      out << "https_port " << cfg.bindAddress << ":" << (cfg.port + 1)
          << " intercept ssl-bump cert=" << cert << " key=" << key
          << " generate-host-certificates=on dynamic_cert_mem_cache_size=4MB\n";
    } else {
      out << "http_port " << cfg.bindAddress << ":" << cfg.port
          << " ssl-bump cert=" << cert << " key=" << key
          << " generate-host-certificates=on dynamic_cert_mem_cache_size=4MB\n";
    }
    out << "acl step1 at_step SslBump1\n";
    out << "ssl_bump peek step1\n";
    out << "ssl_bump bump all\n";
  } else {
    if (cfg.mode == "intercept") {
      out << "http_port " << cfg.bindAddress << ":" << cfg.port << " intercept\n";
    } else {
      out << "http_port " << cfg.bindAddress << ":" << cfg.port << "\n";
    }
  }

  // Access rules: allow all
  out << "\n# Access control\n";
  out << "acl localnet src all\n";
  out << "http_access allow all\n";
  out << "http_reply_access allow all\n";

  // Prepare minimal empty mime table and icon directory
  std::string mimePath = workDir + "/mime.conf";
  std::ofstream mimeOut(mimePath);
  if (mimeOut) {
    mimeOut << "# Empty MIME table for lmproxy\n";
    mimeOut.close();
  }
  out << "mime_table " << mimePath << "\n";

  std::string iconDir = workDir + "/icons";
  mkdir(iconDir.c_str(), 0755);
  out << "icon_directory " << iconDir << "\n";

  // Storage: memory only
  out << "\n# Ephemeral memory-only cache\n";
  out << "cache_mem 32 MB\n";
  out << "maximum_object_size_in_memory 4 MB\n";
  out << "cache allow all\n";

  // Runtime and logs
  out << "\n# Logs and runtime\n";
  out << "pid_filename " << workDir << "/squid.pid\n";
  out << "coredump_dir " << workDir << "\n";
  out << "visible_hostname lmproxy\n";
  out << "logfile_rotate 0\n";
  out << "access_log none\n";
  out << "logfile_daemon /bin/true\n";
  if (cfg.debugLevel > 0) {
    out << "debug_options ALL," << cfg.debugLevel << "\n";
    out << "cache_log stdio:/dev/stderr\n";
  } else {
    out << "cache_log /dev/null\n";
  }

  // Fast forward / connection handling
  out << "forwarded_for delete\n";
  out << "via off\n";
  out << "shutdown_lifetime 1 seconds\n";

  out.close();
  return confPath;
}

